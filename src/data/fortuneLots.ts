// 根据日期字符串获取每日专属一签 (固定 Hash 算法，确保当天唯一)
export const getDailyLotByDate = (dateStr: string): LotItem => {
  let hash = 0;
  for (let i = 0; i < dateStr.length; i++) {
    const char = dateStr.charCodeAt(i);
    hash = (hash << 5) - hash + char;
    hash |= 0;
  }
  const positiveHash = Math.abs(hash);
  const index = positiveHash % ALL_LOTS.length;
  return ALL_LOTS[index];
};
